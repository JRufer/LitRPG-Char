export function getExpForLevel(level: number): number {
  if (level <= 1) return 0;
  if (level >= MAX_LEVEL) return EXP_TABLE[MAX_LEVEL] ?? 15170499;
  return EXP_TABLE[level] ?? 0;
}

export function calculateNextExp(level: number, currentExp: number): number {
  if (level >= MAX_LEVEL) return 0;
  const nextReq = EXP_TABLE[level + 1] ?? (currentExp + 1000);
  return Math.max(0, nextReq - currentExp);
}
