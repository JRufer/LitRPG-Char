pub fn get_exp_for_level(level: u32) -> u64 {
    if level == 0 {
        0
    } else if level >= MAX_LEVEL {
        EXP_TABLE[MAX_LEVEL as usize]
    } else {
        EXP_TABLE[level as usize]
    }
}

pub fn calculate_next_exp(level: u32, current_exp: u64) -> u64 {
    if level >= MAX_LEVEL {
        return 0;
    }
    let next_req = EXP_TABLE[(level + 1) as usize];
    if current_exp >= next_req {
        0
    } else {
        next_req - current_exp
    }
}
